# Literals
print(100)  # int
print(3.14)  # float
print(True)  # bool
print(False)  # bool
print("Hello Python")  # str
print(None)  # NoneType

# A bool is a special kind of integer: True counts as 1, False as 0
print(True + 1)
print(False - 1)

# Output:
# 100
# 3.14
# True
# False
# Hello Python
# None
# 2
# -1
